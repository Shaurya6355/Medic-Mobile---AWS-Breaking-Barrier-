/**
 * compileSnapshot: logic model (DEC-017 v1.json shape) -> CHT project directory that the real
 * cht-conf can compile (forms/app/<id>.xlsx + .properties.json, tasks.js, targets.js,
 * contact-summary.templated.js, app_settings/base_settings.json, .eslintrc, translations).
 *
 * Static files come from ./template (trimmed `cht initialise-project-layout` output); the rest is
 * generated. Output is deterministic: the same model and settings give byte-identical files.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { dangerSignQuestions, modelSha as computeModelSha, type Model } from "../logic/index.js";
import { prepareFlow, type FlowLimits } from "./flowMode.js";
import { buildForm } from "./form.js";
import { checkCompileReady } from "./readiness.js";
import { buildTasks, translationsFile } from "./tasks.js";
import {
  CompileError,
  type BuildKind,
  type CompileSettings,
  type FlowSummary,
  type Manifest,
  type ManifestFile,
  type NotCompiled,
  type Sourcemap,
} from "./types.js";
import { writeFormXlsx } from "./xlsx.js";

export const PREVIEW_README_LINE = "preview build, not approved, not deployable";

export class ApprovalError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ApprovalError";
  }
}

export interface CompileOptions {
  projectDir: string;
  buildKind: BuildKind;
  settings: CompileSettings;
  /** Required for buildKind "release": must equal modelSha(model). */
  approval?: { snapshotSha: string };
  /** Guards on the derived flow's size; exceeding them refuses the compile. Defaults: deriveFlow's. */
  flowLimits?: FlowLimits;
}

const sha256 = (b: Buffer | string) => createHash("sha256").update(b).digest("hex");

export function templateDir(): string {
  return fileURLToPath(new URL("./template/", import.meta.url));
}

function listFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(p);
    }
  };
  walk(dir);
  return out;
}

const posix = (p: string) => p.split(sep).join("/");

function readme(
  model: Model,
  settings: CompileSettings,
  info: { buildKind: BuildKind; version: string; sha: string; warnings: string[]; notCompiled: NotCompiled[]; flow: FlowSummary },
): string {
  const lines = [
    `# ${settings.formTitle}`,
    "",
    `CHT project generated by the logic-model compiler from \`${model.meta.pathway_id}\` version ${model.meta.version}.`,
    "",
  ];
  if (info.buildKind === "preview") lines.push(PREVIEW_README_LINE, "");
  lines.push(
    `- buildKind: ${info.buildKind}`,
    `- form version: ${info.version}`,
    `- modelSha: ${info.sha}`,
    `- guideline: ${model.meta.guideline.title} (${model.meta.guideline.publisher}, ${model.meta.guideline.edition})`,
    "",
    "Compiler settings (form title, icon, team default for the task window, contact types, flow mode) come",
    "from a separate settings JSON, not from the logic model, and are not part of modelSha.",
    "",
    ...flowSection(info.flow),
    "## Warnings",
    "",
    ...(info.warnings.length > 0 ? info.warnings.map((w) => `- ${w}`) : ["- none"]),
    "",
    "## Not compiled",
    "",
    ...(info.notCompiled.length > 0 ? info.notCompiled.map((n) => `- ${n.item}: ${n.reason}`) : ["- none"]),
    "",
    "Do not edit these files by hand: change the logic model or the settings and recompile.",
    "",
  );
  return lines.join("\n");
}

function flowSection(f: FlowSummary): string[] {
  const list = (xs: string[]) => (xs.length > 0 ? xs.join(", ") : "none");
  const avg = `- average questions asked (grid of ${f.points} answer combinations): ${f.avgQuestions.toFixed(2)} (all questions: ${f.avgQuestionsFullForm.toFixed(2)})`;
  const head = ["## Question flow", "", `- flowMode: ${f.mode}`, `- flow derivation version: ${f.derivationVersion}`];
  if (f.mode === "full") {
    return [...head, "- every question its authored shown_when allows is asked (no derived flow)", avg, ""];
  }
  return [
    ...head,
    "",
    "The form asks only the questions that can still change the outcome (one per screen). The flow is derived",
    "from the logic model at compile time (not part of it) and was checked on every grid point: the short form",
    "gives the same outcome as answering every question.",
    "",
    avg,
    `- flow tree: ${f.nodes} nodes, ${f.leaves} leaves, at most ${f.maxDepth} questions on one path`,
    `- always asked: ${list(f.questionsAlwaysAsked)}`,
    `- sometimes skipped: ${list(f.questionsSometimesSkipped)}`,
    `- never asked: ${list(f.neverAsked)}`,
    `- verification: ${f.treeMismatches} tree mismatches, ${f.compiledMismatches} compiled mismatches, ${f.sequenceDifferences} points where the compiled form shows a different sequence than the tree`,
    ...(f.mode === "minimal"
      ? ["- minimal never asks danger-sign questions once the outcome is decided (for example a child outside the age range); flowMode danger_signs_always asks them always"]
      : []),
    "",
  ];
}

export async function compileSnapshot(model: Model, opts: CompileOptions): Promise<Manifest> {
  const { projectDir, buildKind, settings } = opts;
  const sha = computeModelSha(model);

  if (buildKind === "release") {
    if (opts.approval === undefined) throw new ApprovalError("release build needs opts.approval.snapshotSha");
    if (opts.approval.snapshotSha !== sha) {
      throw new ApprovalError(`approval snapshotSha ${opts.approval.snapshotSha} does not match modelSha ${sha}`);
    }
  } else if (buildKind !== "preview") {
    throw new Error(`unknown buildKind ${String(buildKind)}`);
  }

  const ready = checkCompileReady(model, settings);
  if (!ready.compile_ready) {
    throw new CompileError(`model is not compile_ready; missing: ${ready.missing.join("; ")}`, ready);
  }

  if (existsSync(projectDir) && readdirSync(projectDir).length > 0) {
    throw new Error(`project directory is not empty: ${projectDir}`);
  }

  const mode = settings.flowMode ?? "minimal";
  let prepared;
  try {
    prepared = prepareFlow(model, mode, opts.flowLimits);
  } catch (e) {
    if (e instanceof CompileError) {
      throw new CompileError(e.message, { ...ready, compile_ready: false, missing: [...ready.missing, ...e.result.missing] });
    }
    throw e;
  }
  const flowWarnings =
    mode === "danger_signs_always" && dangerSignQuestions(model).length === 0
      ? ["FLOW: flowMode danger_signs_always but the model has no derived value danger_sign; the flow equals minimal"]
      : [];

  const version = `${buildKind}-${sha.slice(0, 8)}`;
  const form = buildForm(model, settings, version, prepared.flow);
  const tasks = buildTasks(model, settings, ready.taskWindows, sha);
  const warnings = [
    ...ready.warnings,
    ...ready.notCompiled.map((n) => `NOT_COMPILED: ${n.item}: ${n.reason}`),
    ...flowWarnings,
  ];
  const sourcemap: Sourcemap = { formId: form.formId, modelSha: sha, flowMode: mode, entries: [...form.sourcemap, ...tasks.sourcemap] };
  const json = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`;

  const generated = new Map<string, Buffer | string>();
  generated.set(`forms/app/${form.formId}.xlsx`, await writeFormXlsx(form));
  generated.set(`forms/app/${form.formId}.properties.json`, json(form.properties));
  generated.set("tasks.js", tasks.js);
  generated.set("translations/messages-en.properties", translationsFile(tasks.translations));
  generated.set("sourcemap.json", json(sourcemap));
  generated.set("README.md", readme(model, settings, { buildKind, version, sha, warnings, notCompiled: ready.notCompiled, flow: prepared.summary }));

  const tpl = templateDir();
  for (const abs of listFiles(tpl)) {
    const rel = posix(relative(tpl, abs));
    if (generated.has(rel)) throw new Error(`template file collides with a generated file: ${rel}`);
    generated.set(rel, readFileSync(abs));
  }

  const files: ManifestFile[] = [];
  for (const rel of [...generated.keys()].sort()) {
    const content = generated.get(rel) as Buffer | string;
    const buf = typeof content === "string" ? Buffer.from(content, "utf8") : content;
    const abs = join(projectDir, ...rel.split("/"));
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, buf);
    files.push({ path: rel, sha256: sha256(buf), bytes: buf.length });
  }

  return {
    files,
    formId: form.formId,
    modelSha: sha,
    buildKind,
    version,
    warnings,
    notCompiled: ready.notCompiled,
    flow: prepared.summary,
    sourcemap,
  };
}
