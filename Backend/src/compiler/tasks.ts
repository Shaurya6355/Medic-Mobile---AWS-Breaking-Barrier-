/**
 * tasks.js generation from scheduled follow-ups (declarative CHT tasks, cht-core reference
 * config/default/tasks.js patterns: getField on the saved report field, a resolvedIf that
 * looks for a later report of the action form inside the event window).
 */
import type { Model, Source } from "../logic/index.js";
import type { CompileSettings, SourcemapEntry } from "./types.js";

export interface BuiltTasks {
  js: string;
  translations: Record<string, string>;
  sourcemap: SourcemapEntry[];
}

/** Single-quoted JS string literal (the CHT nools eslint config requires single quotes). */
export function jsString(s: string): string {
  const body = s
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "\\'")
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .split(String.fromCharCode(0x2028)).join("\\u2028")
    .split(String.fromCharCode(0x2029)).join("\\u2029");
  return `'${body}'`;
}

const HELPERS = `function getField(report, path) {
  return ['fields'].concat((path || '').split('.')).reduce(function (prev, key) {
    return prev === undefined || prev === null ? undefined : prev[key];
  }, report);
}

function addDays(date, days) {
  const result = new Date(date);
  result.setHours(0, 0, 0, 0);
  result.setDate(result.getDate() + days);
  return result;
}

function isFormSubmittedInWindow(reports, form, start, end) {
  return (reports || []).some(function (r) {
    return r.form === form && r.reported_date >= start && r.reported_date <= end;
  });
}

// Resolved when a later report of the same form for the same patient arrives inside the
// event window (same pattern as the cht-core default config tasks.js).
function resolvedByLaterReport(contact, report, event, dueDate) {
  const startTime = Math.max(addDays(dueDate, -event.start).getTime(), report.reported_date + 1);
  const endTime = addDays(dueDate, event.end + 1).getTime();
  return isFormSubmittedInWindow(contact.reports, FORM_ID, startTime, endTime);
}
`;

export function buildTasks(
  model: Model,
  settings: CompileSettings,
  taskWindows: Record<string, number>,
  modelSha: string,
): BuiltTasks {
  const formId = model.meta.pathway_id;
  const translations: Record<string, string> = {};
  const sourcemap: SourcemapEntry[] = [];
  const blocks: string[] = [];

  for (const o of model.outcomes) {
    const fu = o.follow_up;
    if (fu === null || fu.kind !== "scheduled" || fu.due_in_days === null) continue;
    const end = taskWindows[o.id];
    if (end === undefined) continue; // readiness has already refused this model
    const name = `${formId}.${o.id}.follow_up`;
    const titleKey = `task.${formId}.${o.id}.title`;
    translations[titleKey] = `Follow up: ${o.title}`;
    sourcemap.push({
      target: { file: "tasks.js", name },
      kind: "task",
      item: o.id,
      origin: fu.origin,
      sources: (fu.source ?? ([] as Source[])).map((s) => ({ page: s.page, quote: s.quote })),
    });
    blocks.push(`  {
    name: ${jsString(name)},
    icon: ${jsString(settings.icon)},
    title: ${jsString(titleKey)},
    appliesTo: 'reports',
    appliesToType: [FORM_ID],
    appliesIf: function (contact, report) {
      return getField(report, 'outcome') === ${jsString(o.id)};
    },
    resolvedIf: resolvedByLaterReport,
    actions: [{ type: 'report', form: FORM_ID }],
    events: [{ id: ${jsString(`${o.id}-follow-up`)}, days: ${fu.due_in_days}, start: 0, end: ${end} }],
  },`);
  }

  const js = `// Generated by the logic-model compiler from ${formId} (modelSha ${modelSha.slice(0, 8)}). Do not edit by hand.
const FORM_ID = ${jsString(formId)};

${HELPERS}
module.exports = [
${blocks.join("\n")}
];
`;
  return { js, translations, sourcemap };
}

/** messages-en.properties: sorted "key = value" lines. */
export function translationsFile(entries: Record<string, string>): string {
  const esc = (v: string) => v.replace(/\\/g, "\\\\").replace(/\n/g, "\\n").replace(/\r/g, "\\r");
  return Object.keys(entries)
    .sort()
    .map((k) => `${k} = ${esc(entries[k] as string)}\n`)
    .join("");
}
